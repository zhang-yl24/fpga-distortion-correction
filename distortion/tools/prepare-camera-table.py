"""Extract a traceable ST OV5640 DVP/VGA/RGB565 candidate table.

This file is preparation only: it does not configure hardware. Keep the
upstream BSD-3-Clause license and copyright with adapted register settings.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT.parent / "vendor/reference/st-ov5640"
source = (VENDOR / "ov5640.c").read_text()
header = (VENDOR / "ov5640_reg.h").read_text()
symbols = dict(re.findall(r"#define\s+(OV5640_\w+)\s+(0x[0-9a-fA-F]+)U?", header))

def extract(text, name):
    found = re.search(r"\b" + name + r"\s*\[[^;=]*=\s*\{(.*?)\};", text, re.S)
    if not found:
        raise ValueError(f"Missing upstream table {name}")
    pairs = re.findall(r"\{\s*(OV5640_\w+|0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}", found[1])
    if not pairs:
        raise ValueError(f"Empty upstream table {name}")
    result = []
    for symbol, value in pairs:
        address = int(symbols.get(symbol, symbol), 16)
        data = int(value, 16)
        result.append({"address": address, "value": data,
                       "delay_ms_after": 20 if address == 0x3008 else 0})
    return result

sequence = extract(source, "OV5640_Common")
dvp_function = source[source.index("int OV5640_EnableDVPMode("):]
sequence += extract(dvp_function, "regs")
sequence += extract(source, "OV5640_VGA")
sequence += extract(source, "OV5640_PF_RGB565")
# Retain ST's final 4740=23 configuration. Real four-polarity tests on
# 2026-10-06 require inversion of BOTH raw VSYNC and HREF at the receiver.
# New camera2/preview/camera_ddr builds use this verified normalization.
sequence += [{"address": 0x4740, "value": 0x23, "delay_ms_after": 0}]
# Preserve upstream wake-before-DVP ordering. Only enable the eight data
# pads and sync/clock pads physically used by this 24-pin camera module.
# Datasheet: 3017[6:0] VSYNC/HREF/PCLK/D9:6; 3018[7:4] D5:2.
for entry in sequence:
    if entry["address"] == 0x3017:
        entry["value"] = 0x7F
    if entry["address"] == 0x3018:
        entry["value"] = 0xF0
# Configure PLL, dimensions and format before enabling the physical output pads.
# The common table wakes the sensor with pads still disabled. Avoid exposing
# its reset-default clock/format on the connector during reconfiguration.
pads = [e for e in sequence if e['address'] in (0x3017,0x3018)]
sequence = [e for e in sequence if e['address'] not in (0x3017,0x3018)] + pads
sequence += [{"address": 0x3008, "value": 0x02, "delay_ms_after": 20}]
final_registers = {entry["address"]: entry["value"] for entry in sequence}
assert (final_registers[0x3808] << 8 | final_registers[0x3809]) == 640
assert (final_registers[0x380A] << 8 | final_registers[0x380B]) == 480
assert final_registers[0x4300] == 0x6F and final_registers[0x501F] == 1
manifest = json.loads((VENDOR / "sources.json").read_text())
candidate = {
    "status": "candidate_not_applied_or_hardware_verified",
    "requires_silicon_id": "0x5640", "sccb_address_7bit": "0x3C",
    "oscillator_hz_from_module_schematic": 24000000,
    "width": 640, "height": 480, "format_ctrl00": "0x6F",
    "expected_byte_order": "low_byte_first; verify against a real sensor test pattern",
    "board_adaptations": "Upstream wake-before-DVP retained; PLL/format/dimensions configured before pad enable; FREX/GPIO0/GPIO1/D1/D0 pads disabled; 4740=23 retained, receiver must invert raw VSYNC and HREF per real four-polarity tests on 2026-10-06; final stream-on reassertion.",
    "source_repo": manifest["repo"], "source_commit": manifest["commit"],
    "copyright": "Copyright 2019-2020 STMicroelectronics. All rights reserved.",
    "license_file": "../../vendor/reference/st-ov5640/LICENSE.md",
    "limits": "Pixel byte order, actual PCLK/frame rate and image quality require real capture verification.",
    "commands": sequence,
}
dest = ROOT / "board/ov5640-vga-rgb565-candidate.json"
dest.write_text(json.dumps(candidate, indent=2) + "\n")
rom = "// Register settings adapted from STMicroelectronics stm32-ov5640.\n"
rom += "// Copyright 2019-2020 STMicroelectronics. All rights reserved.\n"
rom += "// BSD-3-Clause: see vendor/reference/st-ov5640/LICENSE.md.\n"
rom += "// Generated by prepare-camera-table.py; polarity and pad enable adapted.\n"
rom += f"localparam CAMERA_COMMANDS = {len(sequence)};\n"
rom += "function [31:0] camera_command;\ninput [8:0] index;\nbegin\ncase(index)\n"
rom += "\n".join(f"9'd{i}: camera_command=32'h{e['address']:04x}{e['value']:02x}{e['delay_ms_after']:02x};" for i,e in enumerate(sequence))
rom += "\ndefault: camera_command=32'h00000000;\nendcase\nend\nendfunction\n"
(ROOT / "board/ov5640_commands.vh").write_text(rom)
print(f"Prepared {len(sequence)} reference commands; 640x480 RGB565 candidate, not applied.")
