"""Generate aligned enabled stages for the arithmetic DAG; no map-table ROM.

The integer oracle lives separately in generate-brown-vectors.py. Changing the
pipeline schedule must not change its rounding, saturation, or black-domain rules.
"""
from pathlib import Path

root=Path(__file__).resolve().parents[1]
decl=[];body=[];instances=[];nodes={};delays={};errors={}
def node(name,width,stage):
    nodes[name]=(width,stage);return name
def align(name,stage):
    width,start=nodes[name]
    if stage==start:return name
    assert stage>start
    for s in range(start+1,stage+1):
        key=(name,s)
        if key not in delays:
            n=f'{name}_d{s}';prev=name if s==start+1 else delays[name,s-1]
            decl.append(f'    reg signed [{width-1}:0] {n};')
            body.append(f'            {n}<={prev};');delays[key]=n
    return delays[name,stage]
def reg(name,width,deps,expr,bad=None):
    stage=max(nodes[n][1] for n in deps)+1
    args=[align(n,stage-1) for n in deps]
    decl.append(f'    reg signed [{width-1}:0] {name};')
    body.append(f'            {name}<={expr(*args)};')
    if bad:errors.setdefault(stage,[]).append(bad(*args))
    return node(name,width,stage)
def mul(name,a,b):
    s=max(nodes[a][1],nodes[b][1]);aa,bb=align(a,s),align(b,s)
    decl.append(f'    wire signed [63:0] {name};')
    instances.append(f'    mul32_pipe m_{name}(.clk(clk),.ce(advance),.a({aa}),.b({bb}),.p({name}));')
    return node(name,64,s+3)
def quant32(name,n,shift=22):
    return reg(name,32,[n],lambda a:f'sat32(round{shift}({a}))',lambda a:f'overflow32(round{shift}({a}))')

for n,w in [('in_u',24),('in_v',24),('ocx',24),('ocy',24),('scx',24),('scy',24),('sfx',24),('sfy',24),('ifx',32),('ify',32),('k1',32),('k2',32),('k3',32),('p1',32),('p2',32)]:node(n,w,0)
# Parameters are frame-constant and need no streaming delays.
old_align=align
def align(name,stage):
    return name if name not in ('in_u','in_v') and nodes[name][1]==0 else old_align(name,stage)

du=reg('du',32,['in_u','ocx'],lambda a,b:f'$signed({{{a}[23],{a}}})-$signed({{{b}[23],{b}}})')
dv=reg('dv',32,['in_v','ocy'],lambda a,b:f'$signed({{{a}[23],{a}}})-$signed({{{b}[23],{b}}})')
nxp=mul('nxp',du,'ifx');nyp=mul('nyp',dv,'ify')
nx=reg('nx',32,[nxp],lambda a:f'sat32(round16({a}))',lambda a:f'(round16({a})>65\'sd8388608 || round16({a})< -65\'sd8388608)')
ny=reg('ny',32,[nyp],lambda a:f'sat32(round16({a}))',lambda a:f'(round16({a})>65\'sd8388608 || round16({a})< -65\'sd8388608)')
xxp=mul('xxp',nx,nx);yyp=mul('yyp',ny,ny);xyp=mul('xyp',nx,ny)
xx=quant32('xx',xxp);yy=quant32('yy',yyp);xy=quant32('xy',xyp)
r2=reg('r2',32,[xx,yy],lambda a,b:f'sat32(wide({a})+wide({b}))',lambda a,b:f'overflow32(wide({a})+wide({b}))')
txf=reg('txf',32,[r2,xx],lambda a,b:f'sat32(wide({a})+(wide({b})<<<1))',lambda a,b:f'overflow32(wide({a})+(wide({b})<<<1))')
tyf=reg('tyf',32,[r2,yy],lambda a,b:f'sat32(wide({a})+(wide({b})<<<1))',lambda a,b:f'overflow32(wide({a})+(wide({b})<<<1))')
txa=mul('txa','p1',xy);txb=mul('txb','p2',txf)
tya=mul('tya','p1',tyf);tyb=mul('tyb','p2',xy)
tx=reg('tx',32,[txa,txb],lambda a,b:f'sat32(round22(($signed({a})<<<1)+$signed({b})))',lambda a,b:f'overflow32(round22(($signed({a})<<<1)+$signed({b})))')
ty=reg('ty',32,[tya,tyb],lambda a,b:f'sat32(round22($signed({a})+($signed({b})<<<1)))',lambda a,b:f'overflow32(round22($signed({a})+($signed({b})<<<1)))')
rad=mul('rad0','k3',r2)
h5=reg('h5',32,[rad,'k2'],lambda a,b:f'sat32(round22({a})+wide({b}))',lambda a,b:f'overflow32(round22({a})+wide({b}))')
rad=mul('rad1',h5,r2)
h7=reg('h7',32,[rad,'k1'],lambda a,b:f'sat32(round22({a})+wide({b}))',lambda a,b:f'overflow32(round22({a})+wide({b}))')
rad=mul('rad2',h7,r2)
radial=reg('radial',32,[rad],lambda a:f'sat32(round22({a})+65\'sd4194304)',lambda a:f'overflow32(round22({a})+65\'sd4194304)')
xd=mul('xdp',nx,radial);yd=mul('ydp',ny,radial)
xd=reg('xd',32,[xd,tx],lambda a,b:f'sat32(round22({a})+wide({b}))',lambda a,b:f'overflow32(round22({a})+wide({b}))')
yd=reg('yd',32,[yd,ty],lambda a,b:f'sat32(round22({a})+wide({b}))',lambda a,b:f'overflow32(round22({a})+wide({b}))')
sfx32=reg('sfx32',32,['sfx'],lambda a:f'$signed({a})')
sfy32=reg('sfy32',32,['sfy'],lambda a:f'$signed({a})')
u=mul('up',xd,sfx32);v=mul('vp',yd,sfy32)
ux=reg('result_x',24,[u,'scx'],lambda a,b:f'round22({a})+wide({b})',lambda a,b:f'overflow24(round22({a})+wide({b}))')
vy=reg('result_y',24,[v,'scy'],lambda a,b:f'round22({a})+wide({b})',lambda a,b:f'overflow24(round22({a})+wide({b}))')
length=nodes[ux][1];assert nodes[vy][1]==length
header=f'''`timescale 1ns/1ps
// Generated by tools/prepare-brown-pipeline.py. Signed Q9.22 Brown inverse map.
// Pixel/focal Q15.8, inverse focal Q1.30; nearest rounding, ties to +infinity.
// {length} enabled stages; one ray per cycle. Configuration waits for full drain.
module brown_inverse_mapper #(parameter TAG_W=24)(
    input clk,rst,input cfg_valid,output wire cfg_ready,
    input signed [23:0] cfg_out_cx,cfg_out_cy,cfg_src_cx,cfg_src_cy,cfg_src_fx,cfg_src_fy,
    input signed [31:0] cfg_inv_fx,cfg_inv_fy,cfg_k1,cfg_k2,cfg_k3,cfg_p1,cfg_p2,
    input in_valid,output wire in_ready,input signed [23:0] in_u,in_v,input [TAG_W-1:0] in_tag,
    output wire out_valid,input out_ready,output wire signed [23:0] out_x,out_y,
    output wire out_black,output wire [TAG_W-1:0] out_tag
);
    reg configured;
    reg signed [23:0] ocx,ocy,scx,scy,sfx,sfy;
    reg signed [31:0] ifx,ify,k1,k2,k3,p1,p2;
    reg [{length-1}:0] valid,black;
    reg [TAG_W-1:0] tags[0:{length-1}];
    wire advance /* synthesis syn_maxfan=32 */ = !valid[{length-1}] || out_ready;
    assign cfg_ready=!rst && !(|valid);
    assign in_ready=!rst && advance && configured && !cfg_valid;
    assign out_valid=valid[{length-1}];assign out_tag=tags[{length-1}];assign out_black=black[{length-1}];
    assign out_x=out_black ? 24'sh800000:result_x;
    assign out_y=out_black ? 24'sh800000:result_y;
    function signed [64:0] wide(input signed [31:0] v);wide=v;endfunction
    function signed [64:0] round22(input signed [64:0] v);
        round22=(v>>>22)+$signed({{1'b0,v[21]}});
    endfunction
    function signed [64:0] round16(input signed [64:0] v);
        round16=(v>>>16)+$signed({{1'b0,v[15]}});
    endfunction
    function overflow32(input signed [64:0] v);overflow32=v[64:31]!={{34{{v[31]}}}};endfunction
    function signed [31:0] sat32(input signed [64:0] v);
        sat32=overflow32(v) ? (v[64] ? 32'sh80000000:32'sh7fffffff):v[31:0];
    endfunction
    function overflow24(input signed [64:0] v);overflow24=v[64:23]!={{42{{v[23]}}}};endfunction
'''
control=f'''    integer i;
    always @(posedge clk) begin
        if(rst) begin configured<=0;valid<=0;black<=0;end
        else begin
            if(cfg_valid && cfg_ready) begin
                configured<=1;ocx<=cfg_out_cx;ocy<=cfg_out_cy;scx<=cfg_src_cx;scy<=cfg_src_cy;sfx<=cfg_src_fx;sfy<=cfg_src_fy;
                ifx<=cfg_inv_fx;ify<=cfg_inv_fy;k1<=cfg_k1;k2<=cfg_k2;k3<=cfg_k3;p1<=cfg_p1;p2<=cfg_p2;
            end
            if(advance) begin
                valid<={{valid[{length-2}:0],in_valid && in_ready}};
                black<={{black[{length-2}:0],1'b0}};
                tags[0]<=in_tag;for(i=1;i<{length};i=i+1) tags[i]<=tags[i-1];
'''
for stage,conditions in sorted(errors.items()):
    control+=f"                black[{stage-1}]<="+(f'black[{stage-2}] || ' if stage>1 else '')+' || '.join(conditions)+';\n'
control+='            end\n        end\n    end\n'
# Payload registers need no reset: valid bits suppress stale data after reset.
payload='    always @(posedge clk) if(advance) begin\n'+'\n'.join(body)+'\n    end\nendmodule\n'
(root/'rtl/brown_inverse_mapper.v').write_text(header+'\n'.join(decl)+'\n'+'\n'.join(instances)+'\n'+control+payload)
print(f'Generated {length}-stage Brown mapper, {len(instances)} exact pipelined multipliers')
